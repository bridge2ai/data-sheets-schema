#!/usr/bin/env python3
"""Fail-closed project imports for the U0 causal pair, U0-R7, 2026-11-06.

Inputs: an exact diagnostic root and an ordinary package bootstrap generated by
package_bootstrap() with this helper's SHA-256. Output: a read-only source-origin
inventory for observer start/end; no file writes, provider or native execution.
Install identically in both arms. Never prune an already mixed namespace.
This closes data_sheets_schema imports, not arbitrary third-party startup code:
ordinary Python site/.pth processing has already run and remains separately
declared dependency evidence. Registered argv and production callables remain
unchanged; the diagnostic package __init__.py is an explicit source addition.
"""
from __future__ import annotations

import hashlib
import importlib.machinery
from pathlib import Path
import re
import stat
import sys


PACKAGE = "data_sheets_schema"
HELPER_RELATIVE = "scripts/adhoc/native_u0_source_closure_20261106.py"
PACKAGE_INIT_BYTES = b'"""Diagnostic-only ordinary package: U0-R7 source closure, 2026-11-06."""\n'
_GUARD_ATTRIBUTE = "_d4d_u0_source_closure_finder"


def package_bootstrap(helper_sha256):
    """Bytes for diagnostic src/data_sheets_schema/__init__.py in both arms.

    The parent package is already bound to its exact ordinary-package directory
    when this runs. Verify the helper before executing it, then block editable
    finder fallback before any project child module can be imported.
    """
    if not isinstance(helper_sha256, str) or re.fullmatch(r"[0-9a-f]{64}", helper_sha256) is None:
        raise ValueError("source-closure helper SHA-256 must be lowercase hexadecimal")
    return PACKAGE_INIT_BYTES + (
        "from pathlib import Path as _u0_closure_Path\n"
        "import hashlib as _u0_closure_hashlib\n"
        "import runpy as _u0_closure_runpy\n"
        "_u0_closure_root = _u0_closure_Path(__file__).resolve().parents[2]\n"
        f"_u0_closure_helper = _u0_closure_root / {HELPER_RELATIVE!r}\n"
        f"if _u0_closure_hashlib.sha256(_u0_closure_helper.read_bytes()).hexdigest() != {helper_sha256!r}:\n"
        "    raise RuntimeError('U0 source-closure helper hash differs')\n"
        "_u0_closure_runpy.run_path(str(_u0_closure_helper))['install_source_closure'](_u0_closure_root)\n"
    ).encode()


def _regular_bytes(path):
    path = Path(path)
    before = path.lstat()
    if not stat.S_ISREG(before.st_mode) or path.resolve(strict=True) != path:
        raise RuntimeError("U0 source closure requires an exact regular source file: " + str(path))
    raw = path.read_bytes()
    after = path.lstat()
    fields = ("st_dev", "st_ino", "st_size", "st_mtime_ns", "st_ctime_ns")
    if any(getattr(before, key) != getattr(after, key) for key in fields):
        raise RuntimeError("U0 source changed during origin verification: " + str(path))
    return raw


def _root(root):
    root = Path(root).resolve(strict=True)
    package = root / "src" / PACKAGE
    if not package.is_dir() or package.resolve(strict=True) != package:
        raise RuntimeError("diagnostic package directory is missing or redirected")
    return root, package


def _namespace(name, value, package):
    expected = package.joinpath(*name.split(".")[1:])
    try:
        paths = [Path(item) for item in value]
    except (TypeError, ValueError) as exc:
        raise RuntimeError("malformed project namespace: " + name) from exc
    if (paths != [expected] or any(not path.is_dir() or path.resolve(strict=True) != path for path in paths)):
        raise RuntimeError("project namespace is not the exact diagnostic package: " + name)
    return [str(path) for path in paths]


def _module_identity(name, module, package, *, hash_source):
    if module is None or not hasattr(module, "__dict__"):
        raise RuntimeError("project module is missing or unresolved: " + name)
    values = vars(module)
    spec = values.get("__spec__")
    if spec is None or getattr(spec, "name", None) != name:
        raise RuntimeError("project module spec does not match its name: " + name)
    paths = values.get("__path__")
    locations = getattr(spec, "submodule_search_locations", None)
    row = {"name": name}
    if paths is not None:
        row["namespace"] = _namespace(name, paths, package)
        if locations is None or _namespace(name, locations, package) != row["namespace"]:
            raise RuntimeError("project package spec and namespace disagree: " + name)
    elif locations is not None:
        raise RuntimeError("project module lost its declared package namespace: " + name)
    origin = getattr(spec, "origin", None)
    source = values.get("__file__")
    if source is None:
        if name == PACKAGE or paths is None or origin is not None:
            raise RuntimeError("project module lacks an exact diagnostic source: " + name)
        row.update(file=None, spec_origin=None, namespace_only=True)
        return row
    path = Path(source)
    if (not path.is_absolute() or not path.is_relative_to(package)
            or path.resolve(strict=True) != path or origin != str(path)):
        raise RuntimeError("project module has a foreign or inconsistent source origin: " + name)
    if name == PACKAGE and path != package / "__init__.py":
        raise RuntimeError("root project package is not the diagnostic ordinary package")
    row.update(file=str(path), spec_origin=origin, namespace_only=False)
    if hash_source:
        raw = _regular_bytes(path)
        row.update(bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest())
    return row


def _inventory(root):
    root, package = _root(root)
    helper = root / HELPER_RELATIVE
    helper_raw = _regular_bytes(helper)
    helper_sha = hashlib.sha256(helper_raw).hexdigest()
    # The executing helper must have the same bytes as the declared copy.
    if _regular_bytes(Path(__file__).resolve()) != helper_raw:
        raise RuntimeError("executing source-closure helper differs from diagnostic copy")
    init = package / "__init__.py"
    init_raw = _regular_bytes(init)
    if init_raw != package_bootstrap(helper_sha):
        raise RuntimeError("diagnostic package bootstrap is not the exact hash-bound closure bootstrap")
    selected = [(name, module) for name, module in tuple(sys.modules.items())
                if name == PACKAGE or name.startswith(PACKAGE + ".")]
    if not any(name == PACKAGE for name, _ in selected):
        raise RuntimeError("diagnostic project package has not been bound")
    modules = [_module_identity(name, module, package, hash_source=True)
               for name, module in sorted(selected)]
    return {"format": "native_u0_source_closure_v1", "root": str(root),
            "package_root": str(package), "ordinary_root_package": True,
            "helper": {"path": str(helper), "sha256": helper_sha, "bytes": len(helper_raw)},
            "package_bootstrap": {"path": str(init), "sha256": hashlib.sha256(init_raw).hexdigest(),
                                  "bytes": len(init_raw)},
            "modules": modules, "project_module_count": len(modules),
            "source_scope": "loaded data_sheets_schema modules and exact package-only import resolution",
            "dependency_scope": "stdlib and external packages keep normal finders; prior site/.pth execution and dependency bytes are not attested by this guard",
            "namespace_pruned": False}


class SourceClosureFinder:
    """Resolve only project imports; never fall through to editable finders."""

    def __init__(self, root):
        self.root, self.package = _root(root)

    def find_spec(self, fullname, path=None, target=None):
        if fullname != PACKAGE and not fullname.startswith(PACKAGE + "."):
            return None
        # Do not hash all loaded modules for each import: full inventories belong
        # at observer start/end. Check current root/parent paths on every lookup.
        package_module = sys.modules.get(PACKAGE)
        if package_module is not None:
            _module_identity(PACKAGE, package_module, self.package, hash_source=False)
        if fullname == PACKAGE:
            search = [str(self.root / "src")]
        else:
            parent = fullname.rsplit(".", 1)[0]
            parent_module = sys.modules.get(parent)
            identity = _module_identity(parent, parent_module, self.package, hash_source=False)
            if "namespace" not in identity:
                raise ModuleNotFoundError("No module named '" + fullname + "'; parent is not a package", name=fullname)
            search = identity["namespace"]
            if path is not None and list(path) != search:
                raise RuntimeError("project import path differs from its diagnostic parent: " + fullname)
        spec = importlib.machinery.PathFinder.find_spec(fullname, search, target)
        if spec is None:
            # Returning None would permit a PEP 660 editable finder to load a
            # new primary-checkout child after the diagnostic path was exhausted.
            raise ModuleNotFoundError("No module named '" + fullname + "'", name=fullname)
        if spec.name != fullname:
            raise RuntimeError("project finder returned a mismatched module name")
        if spec.submodule_search_locations is not None:
            _namespace(fullname, spec.submodule_search_locations, self.package)
        if spec.origin is not None:
            origin = Path(spec.origin)
            if (not origin.is_absolute() or not origin.is_relative_to(self.package)
                    or origin.resolve(strict=True) != origin):
                raise RuntimeError("project finder returned a foreign source: " + fullname)
        elif spec.submodule_search_locations is None:
            raise RuntimeError("project finder returned neither local source nor namespace")
        return spec


def _installed(root):
    package = sys.modules.get(PACKAGE)
    finder = vars(package).get(_GUARD_ATTRIBUTE) if package is not None else None
    if (finder is None or finder not in sys.meta_path or sys.meta_path[0] is not finder
            or getattr(finder, "root", None) != root
            or getattr(finder, "package", None) != root / "src" / PACKAGE):
        raise RuntimeError("diagnostic project source guard is not first and active")
    return finder


def assert_source_closure(root):
    """Return observer evidence, refusing mixed origins without mutating them."""
    evidence = _inventory(root)
    _installed(Path(evidence["root"]))
    evidence["project_finder_first"] = True
    return evidence


def install_source_closure(root):
    """Install once at first ordinary-package import; refuse mixed loaded state."""
    evidence = _inventory(root)
    selected = Path(evidence["root"])
    package = sys.modules[PACKAGE]
    if _GUARD_ATTRIBUTE not in vars(package):
        finder = SourceClosureFinder(selected)
        sys.meta_path.insert(0, finder)
        setattr(package, _GUARD_ATTRIBUTE, finder)
    return assert_source_closure(selected)
