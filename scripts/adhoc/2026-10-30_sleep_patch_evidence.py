"""Summarize sleep-patch measurements and refresh only requested CI weights.

Inputs: local JUnit/measurement files from sleep_patch_checks.py, original CI
weights. Outputs: JSON evidence and optional targeted timing updates. Serves
main's red CI run 41092033720; 2026-10-30. Uses the repository's JUnit aggregator.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from utils.update_ci_shard_timings import build
from utils.pytest_shard import balanced_files, partition_lanes, read_weights

RESULTS = ROOT / "test-results" / "sleep-patch"
AFFECTED = {
    "tests.test_report_admission", "tests.test_download.test_api_runner",
    "tests.test_source_review", "tests.test_duplicate_keys", "tests.test_backoff_sleep",
}


def cases(path):
    recorded = []
    for case in ET.fromstring(path.read_bytes()).iter("testcase"):
        skipped = case.find("skipped")
        outcome = ("failed" if case.find("failure") is not None or case.find("error") is not None
                   else "skipped" if skipped is not None else "passed")
        row = {**case.attrib, "outcome": outcome}
        if skipped is not None:
            row["skip_reason"] = skipped.get("message", "")
        recorded.append(row)
    return recorded


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("labels", nargs="+")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--refresh-from", help="Label with a successful full-file or ordinary-shard run")
    parser.add_argument("--files", nargs="*", default=[])
    args = parser.parse_args()
    evidence = {"red_ci_run": 41092033720, "measurements": {}, "diagnosis": {
        "failure": "The shared time-module patch recorded CPython subprocess timeout polls capped at 0.05 seconds.",
        "traced_failure_waits": [
            {"call": "schema_sync._regenerate", "timeout_seconds": 600,
             "origin": "8e20a2a70 (#582): execute's schema-sync gate"},
            {"call": "schema_sync._rebuilt_fingerprint", "timeout_seconds": 600,
             "origin": "edf6fc36fe (#946), merged by 047b3fb3d (#1257)"},
            {"call": "api_runner._validator_lines via receipt_completion._validate_record", "timeout_seconds": 180,
             "origin": "15e8fa88cd (#4266), merged by ec167370d (#4281); validator subprocess existed at 041a368e7d (#361)"},
        ],
        "failing_patch_origin": "0674193f6, merged by fa304cd80 (#5210); the traced subprocess paths predate it.",
        "followup_base": "4c07980399d47d77b64c9f2bff7a50bfc5cc6ddf",
        "merge_resolution": "Use BackoffSleeps consistently at all seven global patch sites in four test files.",
        "timing_limit": "The nine highlighted cases do not install these sleep patches. Serial differences do not establish a patch-induced speedup or test the CI contention hypothesis.",
        "ci_weights": "Unchanged: no reliable material timing change attributable to this follow-up; local host load and a sleep interruption prevent a CI-weight refresh from these measurements.",
        "launcher_corrections": "Native fixtures require test temporaries outside source authority. The first complete shard 6 also found two bytecode-location guard failures: CI requires PYTHONPYCACHEPREFIX outside the checkout. Both temporary files and generated bytecode now use the task's external d4d-executions temporary area; test bodies and production code are unchanged by these launcher corrections.",
    }}
    for label in args.labels:
        directory = RESULTS / label
        measurement_bytes = (directory / "measurement.json").read_bytes()
        measurement = json.loads(measurement_bytes)
        log_bytes = (directory / "pytest.log").read_bytes()
        xml = directory / "pytest.xml"
        recorded = cases(xml)
        measurement.update(measurement_sha256=hashlib.sha256(measurement_bytes).hexdigest(),
                           pytest_log_sha256=hashlib.sha256(log_bytes).hexdigest(),
                           pytest_summary=next(line for line in reversed(log_bytes.decode(errors="replace").splitlines()) if line.strip()),
                           junit_sha256=hashlib.sha256(xml.read_bytes()).hexdigest(),
                           outcomes=dict(Counter(case["outcome"] for case in recorded)),
                           failed_cases=[case for case in recorded if case["outcome"] == "failed"],
                           skipped_cases=[case for case in recorded if case["outcome"] == "skipped"],
                           cases=[case for case in recorded if any(
                               case.get("classname", "") == name or case.get("classname", "").startswith(name + ".")
                               for name in AFFECTED)])
        waits = directory / "waits.json"
        if waits.exists():
            traces = json.loads(waits.read_text())
            measurement["timeout_waits"] = {
                "artifact_sha256": hashlib.sha256(waits.read_bytes()).hexdigest(),
                "calls": sum(row["count"] for row in traces.values()),
                "call_chains": sorted({tuple(re.findall(
                    r'/src/(data_sheets_schema/[^"\n]+)", line (\d+), in ([^\n]+)',
                    row["stack"])) for row in traces.values()}),
            }
        evidence["measurements"][label] = measurement
    comparisons = [("before-nine", "after-nine", "nine_case_comparison"),
                   ("main-4c079-measurement", "followup-measurement", "main_comparison")]
    for before_label, after_label, key in comparisons:
        if not {before_label, after_label}.issubset(evidence["measurements"]):
            continue
        before = evidence["measurements"][before_label]
        after = evidence["measurements"][after_label]
        index = {(row["classname"], row["name"]): row for row in after["cases"]}
        assert len(index) == len(after["cases"]), "comparison requires unique case labels"
        assert set(index) == {(row["classname"], row["name"]) for row in before["cases"]}
        comparison = []
        for old in before["cases"]:
            new = index[(old["classname"], old["name"])]
            comparison.append({"classname": old["classname"], "name": old["name"],
                               "before_seconds": float(old["time"]), "after_seconds": float(new["time"]),
                               "before_outcome": old["outcome"], "after_outcome": new["outcome"]})
        evidence[key] = comparison
        for row in comparison:
            print(f"{row['name']}: {row['before_seconds']:.3f}s -> {row['after_seconds']:.3f}s")
        if key == "main_comparison":
            report_names = {
                "test_a_refused_regate_keeps_the_report_and_the_run_publishes[over_window]",
                "test_exactly_at_the_limit_is_admitted",
            }
            nine = {(row["classname"], row["name"]) for row in comparison
                    if row["classname"].endswith(".TestValidatorRepairRefreshCheckpoint")
                    or (row["classname"] == "tests.test_report_admission" and row["name"] in report_names)}
            assert len(nine) == 9
            groups = {
                "previously_slow_nine": [row for row in comparison if (row["classname"], row["name"]) in nine],
                "validator_checkpoint": [row for row in comparison if row["classname"].endswith(".TestValidatorRepairRefreshCheckpoint")],
                "previously_slow_report_cases": [row for row in comparison
                    if row["classname"] == "tests.test_report_admission" and (row["classname"], row["name"]) in nine],
            }
            assert [len(rows) for rows in groups.values()] == [9, 7, 2]
            evidence["main_comparison_totals"] = {
                name: {"cases": len(rows),
                       "before_seconds": round(sum(row["before_seconds"] for row in rows), 3),
                       "after_seconds": round(sum(row["after_seconds"] for row in rows), 3)}
                for name, rows in groups.items()}
            print(json.dumps(evidence["main_comparison_totals"]))
    power_path = RESULTS / "power-history" / "sleep-events.log"
    if power_path.exists():
        raw = power_path.read_bytes()
        evidence["host_power_history"] = {
            "command": ["/usr/bin/pmset", "-g", "log"],
            "artifact_sha256": hashlib.sha256(raw).hexdigest(),
            "followup_sleep_events": [line for line in raw.decode().splitlines()
                if "2026-10-30 19:16:32" <= line[:19] <= "2026-10-30 20:04:28"],
            "interpretation": "Host sleep interrupted the wire-equivalence case. All seven checkpoint cases had passed by the 19:13:18 process observation; both highlighted report cases ran after the 20:04:28 wake. The nine-case comparison excludes the interrupted case. The original runner's wall_seconds used time.monotonic and excludes deep sleep on this host; pytest's overall summary includes it. Future runs use caffeinate and record both clocks.",
        }
    collections = [label for label in args.labels if label.endswith("collection")]
    if collections:
        collection_label = collections[-1]
        log = (RESULTS / collection_label / "pytest.log").read_text()
        nodes = [line for line in log.splitlines() if re.match(r"^tests/.+\.py::", line)]
        ordinary = partition_lanes(nodes)["ordinary"]
        counts = Counter(node.split("::", 1)[0] for node in ordinary)
        timing_path = ROOT / "utils" / "ci_test_durations.json"
        assignments = balanced_files(counts, 6, read_weights(timing_path))
        evidence["ci_layout"] = {
            "collection_label": collection_label,
            "ci_test_durations_sha256": hashlib.sha256(timing_path.read_bytes()).hexdigest(),
            "collected_cases": len(nodes), "ordinary_cases": len(ordinary),
            "affected_files": {name: {"shard": assignments[name], "cases": count}
                               for name, count in sorted(counts.items())
                               if name[:-3].replace("/", ".") in AFFECTED},
        }
        print(json.dumps(evidence["ci_layout"]))
    if args.refresh_from:
        if not args.files:
            parser.error("--refresh-from requires explicit --files")
        directory = RESULTS / args.refresh_from
        measurement = json.loads((directory / "measurement.json").read_text())
        if measurement["exit_code"] != 0:
            parser.error("timing source must be a successful run")
        # build() sums every JUnit occurrence and rejects failures/duplicates.
        # A local run is not a GitHub run; retain its actual origin separately.
        generated = build(directory, ROOT, None, measurement["commit"])
        selected = {name: generated["file_seconds"][name] for name in args.files}
        timing_path = ROOT / "utils" / "ci_test_durations.json"
        original = json.loads(timing_path.read_text())
        prior = {name: original["file_seconds"].get(name) for name in selected}
        original["file_seconds"].update(selected)
        original["file_seconds"] = dict(sorted(original["file_seconds"].items()))
        origin = {"kind": "local_offline_partial_refresh", "date": "2026-10-30",
                  "base_commit": measurement["commit"], "red_ci_run": 41092033720,
                  "python": measurement["python"], "packages_sha256": measurement["packages_sha256"],
                  "command": measurement["pytest_args"], "label": args.refresh_from,
                  "artifacts": generated["source"]["artifacts"],
                  "file_seconds_before": prior, "file_seconds": selected}
        original.setdefault("local_updates", []).append(origin)
        timing_path.write_text(json.dumps(original, indent=2) + "\n")
        evidence["timing_update"] = origin
        evidence["diagnosis"]["ci_weights"] = "Targeted local refresh using utils.update_ci_shard_timings.build; see timing_update for its provenance."
    final_checks = ("external-cache-canary", "external-bytecode-guards", "external-cache-native-canary",
                    "verified-recorder-regressions", "verified-collection", "final-shard5", "final-shard6")
    evidence["acceptance"] = {
        label: {"commit": row["commit"], "exit_code": row["exit_code"],
                "wall_seconds": row["clock_wall_seconds"], "outcomes": row["outcomes"],
                "pytest_summary": row["pytest_summary"], "skipped_cases": row["skipped_cases"]}
        for label, row in evidence["measurements"].items() if label in final_checks}
    args.output.write_text(json.dumps(evidence, indent=2) + "\n")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
