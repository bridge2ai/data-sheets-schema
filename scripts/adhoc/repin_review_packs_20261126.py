#!/usr/bin/env python3
"""Replace the review packs of one series by the fixed generator's packs, and re-pin.

Purpose: the 15 review packs of release series 2026-11-25c were generated by a
  `d4d review pack` that wrote two absolute paths into each pack (`bundle.manifest`,
  `bundle.resolved_path`; issue #6379). Each review pins its pack by sha256, so the
  paths cannot simply be edited out. This script regenerates each pack in memory with
  the generator that is on the import path (run it with the fixed one), proves that the
  new pack equals the reviewed pack except for those two lines, and only then (with
  --apply) writes the new pack and updates the `pack_sha256` line of the review file.
  The owner chose this route on 2026-11-26. Nothing a reviewer judged changes: every
  item, question, value and sampled slot of the pack is byte-identical.
Inputs (run from the repository root): --method, --config (label prefix). For each
  `<P>_review_pack.yaml` under `data/d4d_concatenated/<method>_core/<label>/`: the
  provenance record, the reviewed pack and the review file beside it.
Outputs: one line per record on stdout; with --apply the rewritten packs and review
  files. Afterwards run `d4d review check --write` for each record, which rewrites the
  provenance `review` block with the new pack and review hashes.
  Exit status 1, and nothing written for any record, if for any record: the reviewed
  pack is not the one its review pins; the regenerated pack differs from it in any line
  other than the two path lines; a path line's new value is not the tail of its old
  value; or the review file does not have exactly one `pack_sha256:` line with the old
  hash. A record whose pack is already the regenerated one is reported and left alone.
Serves: issue #6379, release series 2026-11-25c. Date: 2026-11-26.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import yaml

from data_sheets_schema import review_pack
from data_sheets_schema.provenance import _NoAliasDumper

PATH_KEYS = ("  manifest: ", "  resolved_path: ")


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--method", required=True)
    parser.add_argument("--config", required=True, help="label prefix of the series")
    parser.add_argument("--apply", action="store_true", help="write the packs and update the pins")
    args = parser.parse_args()

    core = Path("data/d4d_concatenated") / f"{args.method}_core"
    plan, problems = [], []
    for old_pack in sorted(core.glob(f"{args.config}*/*_review_pack.yaml")):
        project = old_pack.name[: -len("_review_pack.yaml")]
        where = f"{project} {old_pack.parent.name[-4:]}"
        provenance = old_pack.parent / f"{project}_provenance.yaml"
        review = old_pack.parent / f"{project}_review.yaml"
        old_bytes = old_pack.read_bytes()
        old_sha = sha(old_bytes)
        built = review_pack.build_pack(provenance, None, None, write_instruction=False, instruction_out=[])
        new_text = yaml.dump(built, Dumper=_NoAliasDumper, sort_keys=False, allow_unicode=True, width=10_000)
        new_sha = sha(new_text.encode("utf-8"))
        review_text = review.read_text(encoding="utf-8") if review.is_file() else ""
        pin_lines = [line for line in review_text.splitlines() if line.startswith("pack_sha256:")]
        pinned = pin_lines[0].split(":", 1)[1].strip().strip("'\"") if len(pin_lines) == 1 else None

        if new_sha == old_sha:
            print(f"{where}: already the regenerated pack ({old_sha[:12]}); pinned by its review: {pinned == old_sha}")
            if pinned != old_sha:
                problems.append(f"{where}: the pack is current but the review pins {pinned}")
            continue
        if pinned != old_sha:
            problems.append(f"{where}: the review does not pin the pack on disk (pin {pinned}, pack {old_sha})")
            continue
        old_lines = old_bytes.decode("utf-8").splitlines()
        new_lines = new_text.splitlines()
        if len(old_lines) != len(new_lines):
            problems.append(f"{where}: line counts differ ({len(old_lines)} reviewed, {len(new_lines)} regenerated)")
            continue
        changed = [(number, a, b) for number, (a, b) in enumerate(zip(old_lines, new_lines), 1) if a != b]
        bad = []
        for number, a, b in changed:
            key = next((key for key in PATH_KEYS if a.startswith(key) and b.startswith(key)), None)
            if key is None:
                bad.append(f"line {number} differs and is not a path line")
            elif not a[len(key):].endswith("/" + b[len(key):]):
                bad.append(f"line {number}: the new path is not the tail of the reviewed one")
        if bad or len(changed) != len(PATH_KEYS):
            problems.append(f"{where}: {'; '.join(bad) or f'{len(changed)} lines differ, expected {len(PATH_KEYS)}'}")
            continue
        if review_text.count(f"pack_sha256: {old_sha}") != 1:
            problems.append(f"{where}: the review file does not hold exactly one plain pack_sha256 line with the old hash")
            continue
        plan.append((where, old_pack, new_text, review, review_text, old_sha, new_sha))
        print(f"{where}: {len(changed)} path lines differ, nothing else; {old_sha[:12]} -> {new_sha[:12]}")

    for problem in problems:
        print(f"PROBLEM {problem}", file=sys.stderr)
    if problems:
        print("nothing written", file=sys.stderr)
        return 1
    if args.apply:
        for where, old_pack, new_text, review, review_text, old_sha, new_sha in plan:
            old_pack.write_text(new_text, encoding="utf-8")
            review.write_text(review_text.replace(f"pack_sha256: {old_sha}", f"pack_sha256: {new_sha}"), encoding="utf-8")
        print(f"applied to {len(plan)} record(s); now run d4d review check --write for each")
    else:
        print(f"dry run: {len(plan)} record(s) would be re-pinned")
    return 0


if __name__ == "__main__":
    sys.exit(main())
