#!/usr/bin/env python3
"""Save resumable G2 implementation/evidence state, 2026-11-14.
Inputs: current branch, scratch inventory and explicit active cohort identity.
Output: exclusive checkpoint. No tests, runtime calls, publishing or code edits.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT.parent / 'scratch-g2-20261114'
H2_HEAD = '64fa2b4b7ac2d1b0767e2d89a5ca4109c945229b'


def pin(path):
    raw = path.read_bytes()
    return {'path': str(path), 'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--active-cohort', default='none; implementation and review')
    parser.add_argument('--session', default='none')
    args = parser.parse_args()
    record = {'not_final_handoff': True,
        'head': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        'status': subprocess.check_output(['git', 'status', '--short'], cwd=ROOT, text=True),
        'commits_after_h2': subprocess.check_output(['git', 'log', '--format=%H %s', H2_HEAD + '..HEAD'], cwd=ROOT, text=True).splitlines(),
        'active_cohort': args.active_cohort, 'active_session': args.session,
        'recorded_outcomes': [dict(path=pin(path), outcome=json.loads(path.read_bytes()))
                              for path in sorted(OUT.glob('*/outcome.json'))],
        'evidence': [pin(path) for path in sorted(OUT.glob('*.json'))],
        'constraints': ['Only this assigned branch/worktree; no push, PR, GitHub write, real runtime/probe/capture or provider call.',
                        'Protected files, guard v1 and controller/prompt pins unchanged; 6207 is a review-only proposal.',
                        'Use P/.venv/bin/python with PYTHONPATH=this worktree/src and PYTHONDONTWRITEBYTECODE=1; outputs only sibling scratch.',
                        'No source changes or commits during source-bound test groups. At most four workers; one real canary before a parallel batch.'],
        'remaining_work': ['Complete and commit packet preflight6216 then output separation6224 independently.',
            'Close runner committed-source gap and supply explicit AC fixture for newly reachable early power probe; preserve review findings.',
            'Execute6207 proposal generator only after stable committed source; inspect/apply-check proposed diff without applying any source/pin change.',
            'Run canary then complete touched/module tests; inspect failures, never weaken assertions or production checks. Preserve all cohorts.',
            'Verify and close review findings from actual saved outcomes; preserve generated bytecode after all tests; final protected/pin/source audit.',
            'Write answer-first codex-pr5968-launch-fixes-20261114.md (JSON twin) in assigned R handoffs; print path and computed SHA256.'],
        'handoff_scope': '6217 and6225 remain design proposals; do not claim fixed. Source commits alone are not test proof. H2 handoff is already complete and must not be regenerated at this G2 head.'}
    directory = OUT / 'checkpoints'
    directory.mkdir(exist_ok=True)
    destination = directory / ('g2-' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ') + '.json')
    with destination.open('x') as stream:
        stream.write((json.dumps(record, indent=2) + '\n').replace(chr(64), '\\u0040'))
    print(json.dumps(pin(destination)))


if __name__ == '__main__':
    main()
